async function populateRecipes() {
  try {
    console.log("🚀 Начинаем заполнение базы данных рецептами...");
    console.log(`📝 Всего рецептов: ${RECIPES.length}`);

    const user = auth.currentUser;
    if (!user) {
      console.log("❌ Пользователь не авторизован");
      console.log("Пожалуйста, войдите в аккаунт перед запуском скрипта");
      return;
    }

    console.log(`👤 Пользователь: ${user.email} (${user.uid})`);

    let successCount = 0;
    let errorCount = 0;

    for (let i = 0; i < RECIPES.length; i++) {
      const recipe = RECIPES[i];
      try {
        const caloriesPerGram = recipe.nutritionPer100g.calories / 100;
        
        const recipeData = {
          ...recipe,
          userId: user.uid,
          caloriesPerGram,
          likesCount: 0,
          savesCount: 0,
          averageRating: 0,
          ratingsCount: 0,
          createdAt: Timestamp.now(),
          updatedAt: Timestamp.now(),
        };

        const docRef = await addDoc(collection(db, "recipes"), recipeData);
        console.log(`✅ [${i + 1}/${RECIPES.length}] Добавлен: ${recipe.title}`);
        successCount++;
        
        await new Promise(resolve => setTimeout(resolve, 50));
      } catch (error) {
        console.error(`❌ [${i + 1}/${RECIPES.length}] Ошибка: ${recipe.title}`, error);
        errorCount++;
      }
    }

    console.log("\n📊 СТАТИСТИКА:");
    console.log(`✅ Успешно: ${successCount} рецептов`);
    console.log(`❌ Ошибок: ${errorCount}`);
    console.log(`📝 Всего: ${RECIPES.length} рецептов`);
    
    console.log("\n📋 КАТЕГОРИИ:");
    const categories = new Set<string>();
    const dietTypes = new Set<string>();
    RECIPES.forEach(r => {
      r.categories.forEach(c => categories.add(c));
      dietTypes.add(r.dietType);
    });
    console.log("Категории:", Array.from(categories).sort().join(", "));
    console.log("Типы питания:", Array.from(dietTypes).sort().join(", "));
    
  } catch (error) {
    console.error("❌ Ошибка:", error);
  }
}

async function loginAndPopulate(email: string, password: string) {
  try {
    console.log("🔐 Авторизация...");
    const userCredential = await signInWithEmailAndPassword(auth, email, password);
    console.log(`✅ Вход выполнен: ${userCredential.user.email}`);
    await populateRecipes();
  } catch (error) {
    console.error("❌ Ошибка авторизации:", error);
  }
}